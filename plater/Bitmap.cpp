    Bitmap::Bitmap(int width_, int height_)
        : width(width_), height(height_), sX(0), sY(0), pixels(0), data(NULL),
          maskWords(0), maskValid(false)
    {
        data = new unsigned char[width*height];
        centerX = width/2;
        centerY = height/2;

        for (int x=0; x<width; x++) {
            for (int y=0; y<height; y++) {
                data[BMP_POSITION(x,y)] = false;
            }
        }
    }

    Bitmap::Bitmap(const Bitmap *other)
    {
        width = other->width;
        height = other->height;
        maskWords = 0;
        maskValid = false;
        data = new unsigned char[width*height];

        for (int x=0; x<width; x++) {
            for (int y=0; y<height; y++) {
                data[BMP_POSITION(x,y)] = other->data[BMP_POSITION(x,y)];
            }
        }
    }

    Bitmap::~Bitmap()
    {
        if (data != NULL) {
            delete[] data;
        }
    }

    string Bitmap::toPpm()
    {
        ostringstream oss;
        oss << "P2" << endl;
        oss << "# Generated by Plater - https://github.com/RobotsWar/Plater" << endl;
        oss << width << " " << height << endl;
        oss << "6" << endl;
        for (int y=0; y<height; y++) {
            for (int x=0; x<width; x++) {
                int color = 0;
                switch (data[BMP_POSITION(x,y)]) {
                    case 0:
                        color = 6;
                        break;
                    case 1:
                        color = 4;
                        break;
                    case 2:
                        color = 0;
                        break;
                }
                oss << color;
                if (x+1 != width) {
                    oss << " ";
                }
            }
            oss << "\n";
        }
        return oss.str();
    }

    Bitmap *Bitmap::trim(const Bitmap *bmp)
    {
        bool found = false;
        int minX=0, minY=0;
        int maxX=0, maxY=0;

        for (int x=0; x<bmp->width; x++) {
            for (int y=0; y<bmp->height; y++) {
                if (bmp->getPoint(x, y)) {
                    if (!found) {
                        found = true;
                        minX = maxX = x;
                        minY = maxY = y;
                    } else {
                        if (x < minX) minX = x;
                        if (y < minY) minY = y;
                        if (x > maxX) maxX = x;
                        if (y > maxY) maxY = y;
                    }
                }
            }
        }

        int deltaX = maxX-minX;
        int deltaY = maxY-minY;
        Bitmap *trimmed = new Bitmap(deltaX, deltaY);
        trimmed->centerX = bmp->centerX-minX;
        trimmed->centerY = bmp->centerY-minY;
        for (int x=0; x<deltaX; x++) {
            for (int y=0; y<deltaY; y++) {
                trimmed->setPoint(x, y, bmp->getPoint(x+minX, y+minY));
            }
        }

        return trimmed;
    }

    Bitmap *Bitmap::rotate(const Bitmap *other, float r)
    {
        r = -r;

        float w = other->width;
        float h = other->height;

        int aX = (int)ceil(w*cos(r) - h*sin(r));
        int aY = (int)ceil(w*sin(r) + h*cos(r));

        int bX = (int)ceil(-h*sin(r));
        int bY = (int)ceil(h*cos(r));

        int cX = (int)ceil(w*cos(r));
        int cY = (int)ceil(w*sin(r));

        int xMin = MIN(MIN(0, aX), MIN(bX, cX));
        int xMax = MAX(MAX(0, aX), MAX(bX, cX));
        int yMin = MIN(MIN(0, aY), MIN(bY, cY));
        int yMax = MAX(MAX(0, aY), MAX(bY, cY));

        int width = xMax-xMin;
        int height = yMax-yMin;

        float oldCenterX = other->centerX;
        float oldCenterY = other->centerY;
        float centerX = width/2;
        float centerY = height/2;

        Bitmap *rotated = new Bitmap(width, height);
        for (int x=0; x<width; x++) {
            for (int y=0; y<height; y++) {
                int cX = round(x-centerX);
                int cY = round(y-centerY);
                int X = round((cos(r)*cX - sin(r)*cY) + oldCenterX);
                int Y = round((sin(r)*cX + cos(r)*cY) + oldCenterY);
                rotated->setPoint(x, y, other->getPoint(X, Y));
            }
        }

        return rotated;
    }

    void Bitmap::write(const Bitmap *other, int offx, int offy)
    {
        for (int x=0; x<other->width; x++) {
            for (int y=0; y<other->height; y++) {
                if (other->getPoint(x, y)) {
                    setPoint(x+offx, y+offy, other->getPoint(x, y));
                }
            }
        }
    }

    void Bitmap::ensureMask() const
    {
        if (maskValid) {
            return;
        }
        maskWords = (width + 63) / 64;
        mask.assign((size_t)maskWords * (height > 0 ? height : 0), 0ULL);
        for (int y=0; y<height; y++) {
            uint64_t *row = &mask[(size_t)y * maskWords];
            for (int x=0; x<width; x++) {
                if (data[BMP_POSITION(x,y)]) {
                    row[x >> 6] |= (uint64_t)1 << (x & 63);
                }
            }
        }
        maskValid = true;
    }

    bool Bitmap::overlapsScalar(const Bitmap *other, int offx, int offy) const
    {
        for (int x=0; x<width; x++) {
            for (int y=0; y<height; y++) {
                if (getPoint(x, y) && other->getPoint(x+offx, y+offy)) {
                    return true;
                }
            }
        }
        return false;
    }

    bool Bitmap::overlaps(const Bitmap *other, int offx, int offy)
    {
        ensureMask();
        other->ensureMask();

        const int ow = other->maskWords;
        const int wordShift = offx >> 6;   // whole 64-pixel words to shift
        const int bitShift  = offx & 63;   // sub-word bit shift

        bool hit = false;
        for (int y=0; y<height && !hit; y++) {
            const uint64_t *prow = &mask[(size_t)y * maskWords];
            const uint64_t *qrow = &other->mask[(size_t)(y + offy) * ow];

            for (int w=0; w<maskWords; w++) {
                uint64_t pbits = prow[w];
                if (!pbits) {
                    continue;
                }
                // This part word lands on plate word (w + wordShift), straddling
                // into the next plate word when bitShift != 0.
                int qw = w + wordShift;
                if (qw < ow && (qrow[qw] & (pbits << bitShift))) {
                    hit = true;
                    break;
                }
                if (bitShift) {
                    int qw1 = qw + 1;
                    if (qw1 < ow && (qrow[qw1] & (pbits >> (64 - bitShift)))) {
                        hit = true;
                        break;
                    }
                }
            }
        }

#ifdef PLATER_VERIFY_OVERLAP
        // Optional self-check: abort if the fast path ever disagrees with the
        // scalar reference on real data. Enable with -DPLATER_VERIFY_OVERLAP.
        if (hit != overlapsScalar(other, offx, offy)) {
            fprintf(stderr, "OVERLAP MISMATCH at off=(%d,%d)\n", offx, offy);
            abort();
        }
#endif
        return hit;
    }

    void Bitmap::dilatation(int iterations)
    {
        for (int i=0; i<iterations; i++) {
            Bitmap old(this);
            for (int x=0; x<width; x++) {
                for (int y=0; y<height; y++) {
                    if (!old.getPoint(x, y)) {
                        int score = 0;
                        for (int dx=-1; dx<=1; dx++) {
                            for (int dy=-1; dy<=1; dy++) {
                                if (old.getPoint(x+dx, y+dy)) {
                                    score++;
                                }
                            }
                        }
                        if (score >= 1) {
                            setPoint(x, y, 1);
                        }
                    }
                }
            }
        }
    }
